#!/usr/bin/env python3
"""Build the email library: validate sections and recipes, assemble every template, write the catalogues.

Usage:
  build_library.py [--root REPO] [--check] [--screenshots [ID ...]]

The library lives in the repository:
  templates/email-blocks/<id>/section.html + section.json   (Sections database, edited by hand)
  templates/emails/<slug>/template.json                      (Templates database; "sections" = ordered recipe)
Generated (never edit by hand):
  templates/emails/<slug>/template.html | template.liquid.html | custom-liquid/NN.html
  README.md + index.tsv in both folders, README.md in every section and template folder.

--check        fail (exit 1) if any generated text file is missing or stale; writes nothing.
--screenshots  also re-render preview.png for the given section/template ids (all when no id is
               given). Needs Google Chrome and Pillow; see screenshot_block.py.
"""
import argparse
import json
import pathlib
import subprocess
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import assemble_email  # noqa: E402
import lint_email  # noqa: E402
import re  # noqa: E402
import v6_html  # noqa: E402

BANK_THEMES = ('bone', 'ink', 'white')
BANK_FONTS = ('Inter', 'Inter Tight', 'Playfair Display', 'JetBrains Mono', 'Arial', 'Helvetica', 'sans-serif',
              'Georgia', 'Times New Roman', 'serif', 'Courier New', 'monospace')

SURFACE_MODE = {"notification": "notification", "messaging-code-your-own": "code-your-own",
                "messaging-sections": "sections"}
SURFACE_LABEL = {"notification": "Notification template", "messaging-code-your-own": "Messaging · Code your own",
                 "messaging-sections": "Messaging · Custom Liquid sections",
                 "messaging-section": "Messaging section"}
SURFACE_CONTEXT = {"notification": "order", "messaging-code-your-own": "abandoned-checkout",
                   "messaging-sections": "abandoned-checkout"}
SECTION_KEYS = {"name", "type", "context", "surfaces", "liquid_variables", "placeholders", "notes"}
# "context" is optional on a template: it defaults to SURFACE_CONTEXT[surface]. Marketing emails that are not
# abandoned-checkout sends (welcome, win-back, reorder, newsletters) set "context": "customer".
OPTIONAL_TEMPLATE_KEYS = {"context", "html_title"}
TEMPLATE_KEYS = {"code", "name", "journey", "surface", "shopify_location", "subject", "preview_text", "timing",
                 "shopify_status", "shopify_matches_repo", "blockers", "sections"}
GEN_NOTE = "<!-- Generated by .claude/skills/shopify-email-html/scripts/build_library.py — edit section.json / template.json instead. -->\n"


def template_context(t):
    return t.get("context") or SURFACE_CONTEXT[t["surface"]]


def load(root):
    blk, eml = root / "templates/email-blocks", root / "templates/emails"
    errors, sections, templates = [], {}, {}
    for d in sorted(p for p in blk.iterdir() if p.is_dir()):
        try:
            meta = json.loads((d / "section.json").read_text())
            html = (d / "section.html").read_text(encoding="utf-8")
        except (OSError, json.JSONDecodeError) as e:
            errors.append(f"section {d.name}: {e}")
            continue
        missing = SECTION_KEYS - meta.keys()
        if missing:
            errors.append(f"section {d.name}: section.json lacks {sorted(missing)}")
        sections[d.name] = {"id": d.name, "dir": d, "html": html, **meta}
    for d in sorted(p for p in eml.iterdir() if p.is_dir()):
        try:
            meta = json.loads((d / "template.json").read_text())
        except (OSError, json.JSONDecodeError) as e:
            errors.append(f"template {d.name}: {e}")
            continue
        missing = TEMPLATE_KEYS - meta.keys()
        if missing:
            errors.append(f"template {d.name}: template.json lacks {sorted(missing)}")
            continue
        templates[d.name] = {"id": d.name, "dir": d, **meta}
    return sections, templates, errors


def validate_bank(sections):
    """Module bank rules (sections with a `bank` key): one card, v6 palette and fonts, no coral text on light
    surfaces, and every module present in all three themes."""
    errors, modules = [], {}
    for s in sections.values():
        b = s.get("bank")
        if not b:
            continue
        sid, html = s["id"], s["html"]
        modules.setdefault((b["category"], b["module"]), set()).add(b["theme"])
        if html.count("border-radius:12px") != 1:
            errors.append(f"bank section {sid}: expected exactly one 12px card, found {html.count('border-radius:12px')}")
        for hx in sorted(set(re.findall(r"#[0-9a-fA-F]{6}\b", html))):
            if hx.lower() not in v6_html.PALETTE:
                errors.append(f"bank section {sid}: colour {hx} is not in the v6 palette")
        for fam in re.findall(r"font-family:([^;\"]+)", html):
            for f in re.split(r",", fam):
                f = f.strip().strip("'\"")
                if f and f not in BANK_FONTS:
                    errors.append(f"bank section {sid}: font {f!r} is not a v6 font")
        if b["theme"] != "ink" and re.search(r"(?<![-\w])color:#ff5757", html, re.I):
            errors.append(f"bank section {sid}: coral text on a {b['theme']} surface fails contrast; coral text is Ink-only")
        if b["theme"] not in BANK_THEMES:
            errors.append(f"bank section {sid}: unknown theme {b['theme']!r}")
    for (cat, mod), themes in modules.items():
        if themes != set(BANK_THEMES):
            errors.append(f"bank module {mod!r}: has themes {sorted(themes)}, needs {sorted(BANK_THEMES)}")
    return errors


def validate(sections, templates):
    errors = validate_bank(sections)
    for s in sections.values():
        if s.get("type") in ("Email head", "Liquid header"):
            continue
        errs, _ = lint_email.lint(s["html"], "section")
        errors += [f"section {s['id']}: {e}" for e in errs]
    for t in templates.values():
        if t["surface"] not in SURFACE_MODE:
            errors.append(f"template {t['id']}: unknown surface {t['surface']!r}")
            continue
        for sid in t["sections"]:
            s = sections.get(sid)
            if not s:
                errors.append(f"template {t['id']}: unknown section {sid!r}")
                continue
            ctx = template_context(t)
            if s["context"] not in ("any", ctx):
                errors.append(f"template {t['id']}: section {sid} reads {s['context']} data, "
                              f"but this {t['surface']} email only has {ctx} data")
        if len(set(t["sections"])) != len(t["sections"]):
            errors.append(f"template {t['id']}: a section is listed twice")
    return errors


def assemble(t, sections):
    texts = [sections[sid]["html"] for sid in t["sections"]]
    mode = SURFACE_MODE[t["surface"]]
    title = t.get("html_title") or (t["subject"] if "{" not in t["subject"] else t["name"])
    result = assemble_email.build(mode, texts, title, t["preview_text"])
    if mode == "sections":
        return {f"custom-liquid/{i:02d}.html": sec for i, sec in enumerate(result, 1)}
    name = "template.liquid.html" if mode == "notification" else "template.html"
    return {name: result}


def status_of(sid, templates):
    used = [t for t in templates.values() if sid in t["sections"]]
    if any(t["shopify_status"] == "live" for t in used):
        return "live"
    return "draft" if used else "unused"


def img(path, width):
    return f'<img src="{path}" width="{width}" alt="">' if path else "—"


def section_readme(s, templates):
    used = [t for t in templates.values() if s["id"] in t["sections"]]
    rows = [("Type", s["type"]), ("Context", s["context"]),
            ("Surfaces", ", ".join(SURFACE_LABEL.get(x, x) for x in s["surfaces"])),
            ("Liquid variables", ", ".join(f"`{v}`" for v in s["liquid_variables"]) or "—"),
            ("Shopify status", status_of(s["id"], templates)),
            ("Placeholders", "yes — do not ship as is" if s["placeholders"] else "no"),
            ("Characters", str(len(s["html"]))),
            ("Used by", ", ".join(f"[{t['code']}](../../emails/{t['id']}/)" for t in used) or "—")]
    out = [GEN_NOTE, f"# {s['name']}\n", "| | |\n|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    if s["notes"]:
        out.append(f"\n> {s['notes']}")
    b = s.get("bank")
    if b:
        out.append(f"\n## Module bank\n\n- Category: {b['category']}\n- Module: {b['module']} · theme **{b['theme']}**"
                   f"\n- Figma source: [{b['figma_source']}]({b['figma_node']})")
        out.append("\n**Changed from the Figma module to meet the v6 rules**\n")
        out += [f"- {a}" for a in b["adaptations"]]
        out.append("\n**Figma sample copy (reference only, not in the section)**: " + " · ".join(b["sample_copy"]))
    if (s["dir"] / "preview.png").exists():
        out.append("\n## Preview\n\n" + img("preview.png", 600))
    out.append("\n## HTML\n\nSource: [`section.html`](section.html). Copy from here or from the raw file.\n")
    out.append("```html\n" + s["html"].rstrip() + "\n```\n")
    return "\n".join(out)


def template_readme(t, sections, outputs):
    rows = [("Code", t["code"]), ("Journey", t["journey"]), ("Surface", SURFACE_LABEL[t["surface"]]),
            ("Where in Shopify", t["shopify_location"]), ("Subject", f"`{t['subject']}`"),
            ("Preview text", t["preview_text"]), ("Timing", t["timing"]),
            ("Shopify status", t["shopify_status"]),
            ("Shopify matches this repo", "yes" if t["shopify_matches_repo"] else "**no — re-sync Shopify from the file below**")]
    out = [GEN_NOTE, f"# {t['code']} · {t['name']}\n", "| | |\n|---|---|"]
    out += [f"| {k} | {v} |" for k, v in rows]
    out.append("\n## Sections (assembly order)\n")
    out += [f"{i}. [{sections[sid]['name']}](../../email-blocks/{sid}/) — `{sid}`" for i, sid in enumerate(t["sections"], 1)]
    out.append("\n## Code to install\n")
    if t["surface"] == "messaging-sections":
        out.append("One Shopify Messaging **Custom Liquid** section per file, in this order:\n")
        out += [f"- [`{p}`]({p})" for p in outputs]
    else:
        out += [f"- [`{p}`]({p})" for p in outputs]
    if t["blockers"]:
        out.append("\n## Open blockers\n")
        out += [f"- {b}" for b in t["blockers"]]
    if (t["dir"] / "preview.png").exists():
        out.append("\n## Preview\n\n" + img("preview.png", 600))
    out.append("\n## Rebuild\n\nEdit `template.json` (`sections` is the recipe) or a section, then run "
               "`python3 .claude/skills/shopify-email-html/scripts/build_library.py` from the repo root.\n")
    return "\n".join(out)


def tsv(rows):
    clean = lambda v: str(v).replace("\t", " ").replace("\n", " ")
    return "\n".join("\t".join(clean(v) for v in r) for r in rows) + "\n"


def bank_catalogue(sections):
    bank = [s for s in sections.values() if s.get("bank")]
    if not bank:
        return {}
    rows = [["id", "category", "module", "theme", "type", "characters"]]
    rows += [[s["id"], s["bank"]["category"], s["bank"]["module"], s["bank"]["theme"], s["type"], len(s["html"])] for s in bank]
    mods = {}
    for s in bank:
        mods.setdefault(s["bank"]["category"], {}).setdefault(s["bank"]["module"], {})[s["bank"]["theme"]] = s
    n_mod = sum(len(m) for m in mods.values())
    g = [GEN_NOTE, "# Email module bank\n",
         f"{n_mod} modules in three real themes each (Bone, Ink, White): **{len(bank)} Shopify Messaging Custom Liquid sections**, "
         "each one card (12px corners, flush, transparent outside), built to the v6 email design system from the Figma "
         "module library. Copy is a labelled slot (`[Headline]`): replace it before use.\n",
         "Every section is generated by [`templates/module-bank/build_bank.py`](../module-bank/build_bank.py); change the module "
         "function, never the section files. Sortable table: [`bank.tsv`](bank.tsv). How to use and extend it: "
         "[`references/module-bank.md`](../../.claude/skills/shopify-email-html/references/module-bank.md).\n"]
    for cat in sorted(mods):
        g.append(f"\n## {cat}\n\n| Module | Bone | Ink | White |\n|---|---|---|---|")
        for mod, themes in mods[cat].items():
            cells = []
            for t in BANK_THEMES:
                sec = themes.get(t)
                if not sec:
                    cells.append("—")
                    continue
                pv = img(f"{sec['id']}/preview.png", 260) if (sec["dir"] / "preview.png").exists() else "no preview"
                cells.append(f"[{pv}]({sec['id']}/)<br>`{sec['id']}`")
            g.append(f"| **{mod}** | " + " | ".join(cells) + " |")
    return {"templates/email-blocks/BANK.md": "\n".join(g) + "\n", "templates/email-blocks/bank.tsv": tsv(rows)}


def catalogues(sections, templates):
    files = bank_catalogue(sections)
    all_sections, sections = sections, {k: v for k, v in sections.items() if not v.get("bank")}
    srows = [["id", "name", "type", "context", "surfaces", "status", "placeholders", "used_by", "characters"]]
    for s in sections.values():
        used = ",".join(t["code"] for t in templates.values() if s["id"] in t["sections"])
        srows.append([s["id"], s["name"], s["type"], s["context"], ",".join(s["surfaces"]),
                      status_of(s["id"], templates), "yes" if s["placeholders"] else "no", used, len(s["html"])])
    files["templates/email-blocks/index.tsv"] = tsv(srows)
    g = [GEN_NOTE, "# Email sections\n",
         "The sections database: every reusable block of a Shopify email, with its exact HTML and a preview. "
         "Each folder holds `section.html` (the code), `section.json` (its properties) and `preview.png`.\n",
         "Sortable table: [`index.tsv`](index.tsv). Templates that use these sections: [`../emails/`](../emails/). "
         "The module bank (every favourite module in Bone, Ink and White) has its own gallery: [`BANK.md`](BANK.md).\n",
         "All previews are 1200px wide (600px email at 2×). Every card stacks flush with the next one "
         "(no gap), has 12px corners and no background behind it.\n"]
    by_type = {}
    for s in sections.values():
        by_type.setdefault(s["type"], []).append(s)
    for typ, items in by_type.items():
        g.append(f"\n## {typ}\n\n| Preview | Section | Context | Used by | Status |\n|---|---|---|---|---|")
        for s in items:
            pv = img(f"{s['id']}/preview.png", 260) if (s["dir"] / "preview.png").exists() else "— (no visual output)"
            used = ", ".join(f"[{t['code']}](../emails/{t['id']}/)" for t in templates.values() if s["id"] in t["sections"])
            warn = " ⚠️ placeholder" if s["placeholders"] else ""
            g.append(f"| {pv} | [{s['name']}]({s['id']}/)<br>`{s['id']}`{warn} | {s['context']} | {used or '—'} | "
                     f"{status_of(s['id'], templates)} |")
    files["templates/email-blocks/README.md"] = "\n".join(g) + "\n"
    trows = [["id", "code", "name", "journey", "surface", "shopify_status", "shopify_matches_repo", "subject",
              "timing", "sections"]]
    for t in templates.values():
        trows.append([t["id"], t["code"], t["name"], t["journey"], t["surface"], t["shopify_status"],
                      "yes" if t["shopify_matches_repo"] else "no", t["subject"], t["timing"], ",".join(t["sections"])])
    files["templates/emails/index.tsv"] = tsv(trows)
    g = [GEN_NOTE, "# Email templates\n",
         "The templates database: every assembled Shopify email. A template is a recipe — the ordered list of "
         "sections in `template.json` — and the build turns it into the code you paste into Shopify.\n",
         "Sortable table: [`index.tsv`](index.tsv). Sections: [`../email-blocks/`](../email-blocks/).\n",
         "| Preview | Template | Surface | Shopify | Sections |\n|---|---|---|---|---|"]
    for t in templates.values():
        pv = img(f"{t['id']}/preview.png", 200) if (t["dir"] / "preview.png").exists() else "—"
        sync = "" if t["shopify_matches_repo"] else "<br>⚠️ Shopify out of date"
        g.append(f"| {pv} | [{t['code']} · {t['name']}]({t['id']}/)<br>{t['timing']} | {SURFACE_LABEL[t['surface']]} | "
                 f"{t['shopify_status']}{sync} | {len(t['sections'])} |")
    files["templates/emails/README.md"] = "\n".join(g) + "\n"
    return files


def screenshot(src, out, fixture, head=None, prefix=None, full=False):
    cmd = [sys.executable, str(HERE / "screenshot_block.py"), str(src), "-o", str(out)]
    if fixture:
        cmd += ["--fixture", str(fixture)]
    if head:
        cmd += ["--head", str(head)]
    if prefix:
        cmd += ["--prefix", str(prefix)]
    if full:
        cmd.append("--full")
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        raise RuntimeError(r.stderr.strip() or r.stdout.strip())
    print(r.stdout.strip())


def take_screenshots(root, sections, templates, ids):
    import tempfile
    assets = HERE.parent / "assets"
    fixture = lambda ctx: assets / f"fixture-{ctx}.json" if ctx != "any" else assets / "fixture-abandoned-checkout.json"
    head = next((s for s in sections.values() if s["type"] == "Email head"), None)
    for s in sections.values():
        if ids and s["id"] not in ids or s["type"] in ("Email head", "Liquid header"):
            continue
        prefix = None
        if s["context"] == "order":
            for t in templates.values():
                if s["id"] in t["sections"]:
                    prefix = next((sections[x]["dir"] / "section.html" for x in t["sections"]
                                   if sections[x]["type"] == "Liquid header"), None)
                    break
        screenshot(s["dir"] / "section.html", s["dir"] / "preview.png", fixture(s["context"]),
                   head=head["dir"] / "section.html" if head else None, prefix=prefix)
    for t in templates.values():
        if ids and t["id"] not in ids:
            continue
        doc = assemble_email.build("notification" if t["surface"] == "messaging-sections" else SURFACE_MODE[t["surface"]],
                                   [sections[x]["html"] for x in t["sections"]], t["name"])
        with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False, encoding="utf-8") as f:
            f.write(doc)
        try:
            screenshot(f.name, t["dir"] / "preview.png", fixture(template_context(t)), full=True)
        finally:
            pathlib.Path(f.name).unlink()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(HERE.parents[3]), help="repository root (default: inferred)")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--screenshots", nargs="*")
    a = ap.parse_args()
    root = pathlib.Path(a.root).resolve()
    if not (root / "templates/email-blocks").is_dir():
        sys.exit(f"ERROR: {root} has no templates/email-blocks; pass --root")
    sections, templates, errors = load(root)
    errors += validate(sections, templates)
    if errors:
        for e in errors:
            print(f"ERROR {e}", file=sys.stderr)
        sys.exit(1)
    if a.screenshots is not None and not a.check:
        try:
            take_screenshots(root, sections, templates, set(a.screenshots))
        except (RuntimeError, assemble_email.AssemblyError) as e:
            sys.exit(f"ERROR screenshot: {e}")
    files = {}
    for t in templates.values():
        try:
            outputs = assemble(t, sections)
        except assemble_email.AssemblyError as e:
            sys.exit(f"ERROR template {t['id']}: {e}")
        rel = t["dir"].relative_to(root)
        for name, text in outputs.items():
            files[str(rel / name)] = text
        files[str(rel / "README.md")] = template_readme(t, sections, list(outputs))
    for s in sections.values():
        files[str(s["dir"].relative_to(root) / "README.md")] = section_readme(s, templates)
    files.update(catalogues(sections, templates))
    stale = [p for p, text in files.items()
             if not (root / p).exists() or (root / p).read_text(encoding="utf-8") != text]
    if a.check:
        for p in stale:
            print(f"STALE {p}", file=sys.stderr)
        if stale:
            sys.exit(f"ERROR: {len(stale)} generated file(s) out of date; run build_library.py")
        print(f"OK {len(sections)} sections, {len(templates)} templates, all generated files current")
        return
    for p in stale:
        (root / p).parent.mkdir(parents=True, exist_ok=True)
        (root / p).write_text(files[p], encoding="utf-8")
    print(f"{len(sections)} sections, {len(templates)} templates; wrote {len(stale)} file(s)")


if __name__ == "__main__":
    main()
